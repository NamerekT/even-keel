import { EARLY_STEPS } from './database-steps-early.js'

/**
 * Numbered schema steps: STEPS[n] takes the database from version SQLITE_VERSIONS + n to the next one, in one transaction
 * with the new version; an empty database runs them all. A step is never edited or removed once merged: a schema change
 * is a new step. A project is named by its id (`projects[].id` of the config); the JSON columns hold what the code keeps
 * as it is. Step 3 is the tables of the SQLite versions in Postgres; step 4 the project records and the settings
 * (BTN-199), `unattended` and `trimTools` moving from `chain_flags` into Even Keel's setting rows; step 5 the tracker
 * profiles and each project's profile (BTN-200); step 6 the versions of the milestones' changelog drafts (BTN-209); step 7 what each version's turn cost; step 8 the chain's list of pull requests, `reviews` (BTN-205); step 9 gives each project the color its position had,
 * a `color` row (BTN-207); step 12 the profiles' chain rules, the projects' extra task feeds and each feed's profile,
 * and the profile and status of an archived task (BTN-66); step 13 gives each project without a `tracker` row of its own
 * the one it ran on — Even Keel's row, else `huly`, the default of then — and drops Even Keel's (BTN-345); step 14 the
 * organization each API account's key pays through, `key_organizations` (BTN-418); step 21 puts the Agent SDK of
 * Claude on the checked CLI (BTN-610); step 22 the `reason` of a chat message that came back (BTN-558); step 23 copies a project's own chain rules into each
 * of its feeds (BTN-553); step 24 the profiles' status moves (BTN-554); step 25 each account's last known limits,
 * `account_limits` (BTN-631); step 26 the tasks the merge closer closed, `merge_closes` (BTN-689); step 29 the event
 * log, `event_log` (BTN-350); step 30 the built-in tracker, `builtin_*` (BTN-767); step 32 its attachments, `builtin_files` (BTN-773); step 43 the worktree folders a cleanup left held, `left_folders` (BTN-925); step 49 the copy of a built-in project's tasks into another tracker, `tracker_exports` and `tracker_export_tasks` (BTN-1073); step 50 the copied project's old key, `tracker_exports.source_key` (BTN-1076); step 52 the machines of each project and the machine of each task, `project_machines` and `machine_tasks` (BTN-1216); step 53 the handoff notes, `handoff_notes` (BTN-1046); step 54 the project memory, `memory_records` (BTN-1029); step 57 the tasks moved by hand off a machine gone, `task_moves` (BTN-1270); step 58 a pool machine's own folder of the project, `project_machines.folder` (BTN-1271); step 59 a machine's colour, `machines.color` (BTN-1272). A foreign key between tables is deferred, so that a copy inserts the
 * tables in any order (`insertRows`).
 */

import { execFile } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { promisify } from 'node:util'
import { protectionRules, type Protection } from '../sessions/protection.js'
import { fail } from '../notice/notice.js'

const run = promisify(execFile)
const HEADER = '# Generated by Even Keel. Updated before a session turn.\n'
const NAME = 'even-keel.generated.rules'

/** A worktree's own config layer keeps different projects and accounts from changing each other's deny rules. */
export async function writeProtection(cwd: string, value: Protection, mainBranch?: string): Promise<void> {
  const call = (args: string[]) => run('git', ['-C', cwd, ...args], { timeout: 10_000, windowsHide: true })
  const remotes = await call(['remote']).then(answer => answer.stdout.trim().split(/\r?\n/).filter(Boolean), () => [])
  const rules = protectionRules(value, remotes, mainBranch).codex
  const dir = join(cwd, '.codex', 'rules')
  const path = join(dir, NAME)
  const previous = await readFile(path, 'utf8').catch((error: NodeJS.ErrnoException) => { if (error.code === 'ENOENT') return ''; throw error })
  if (previous !== '' && !previous.startsWith(HEADER)) throw fail('protection.fileConflict', {}, { detail: path })
  const text = HEADER + rules.map(pattern => `prefix_rule(pattern=${JSON.stringify(pattern)}, decision="forbidden")\n`).join('')
  const exclude = await call(['rev-parse', '--path-format=absolute', '--git-path', 'info/exclude'])
  const excludePath = exclude.stdout.trim()
  const ignored = await readFile(excludePath, 'utf8').catch((error: NodeJS.ErrnoException) => { if (error.code === 'ENOENT') return ''; throw error })
  const entry = `/.codex/rules/${NAME}`
  if (!ignored.split(/\r?\n/).includes(entry)) await writeFile(excludePath, `${ignored}\n${entry}\n`)
  await mkdir(dir, { recursive: true })
  if (text !== previous) await writeFile(path, text)
}

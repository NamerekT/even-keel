import type { PGlite } from '@electric-sql/pglite'
import { inTransaction, openDatabase } from '../storage/database.js'
import type { MachineEvent } from './protocol.js'

/** A project the machine agreed to serve and a folder of it: a command is run only inside these. */
export interface Consent {
  project: string
  folder: string
}

/**
 * What a machine keeps about its link: the events its hub has not confirmed, the numbers of the commands it took
 * and the projects and folders it agreed to. It belongs to one connection token: a machine set up anew takes a new one.
 */
export interface MachineStore {
  /** Keeps the event under the next number. */
  appendEvent(type: string, at: number, payload?: unknown): Promise<MachineEvent>
  eventsAfter(seq: number, limit: number): Promise<MachineEvent[]>
  /** The hub took the events up to this number; the numbering goes on past it, whatever the store held. */
  dropEvents(upTo: number): Promise<void>
  /** The highest command number taken, 0 — none yet. */
  lastCommand(): Promise<number>
  /** Records the command before it runs; `false` — a number at or below the last one, a repeat. */
  commandReceived(seq: number, at: number): Promise<boolean>
  commandDone(seq: number, at: number): Promise<void>
  /** The commands recorded and never finished: the machine stopped in the middle of them. */
  unfinishedCommands(): Promise<number[]>
  consents(): Promise<Consent[]>
  agree(project: string, folder: string): Promise<void>
  /** Without a folder — the whole project. */
  withdraw(project: string, folder?: string): Promise<void>
}

/** How many finished commands the store keeps, for a look at what the machine ran last. */
export const KEPT_COMMANDS = 200

/** The machine database's own schema steps, numbered like the state database's: never edit a merged one. */
export const MACHINE_STEPS: readonly string[] = [
  `
  create table outbox (
    seq     bigint generated by default as identity primary key,
    type    text not null,
    at      bigint not null,
    payload text
  );
  create table commands (
    seq         bigint primary key,
    received_at bigint not null,
    done_at     bigint
  );
  create table consents (
    project_id text not null,
    folder     text not null,
    primary key (project_id, folder)
  );
  `,
]

/** The machine's database in `dataDir` (in memory without one), brought to its current schema. */
export const openMachineDatabase = (dataDir: string | undefined): Promise<PGlite> => openDatabase(dataDir, MACHINE_STEPS)

interface EventRow {
  seq: string
  type: string
  at: string
  payload: string | null
}

export class DatabaseMachineStore implements MachineStore {
  constructor(private readonly db: PGlite) {}

  async appendEvent(type: string, at: number, payload?: unknown): Promise<MachineEvent> {
    const { rows } = await this.db.query<{ seq: string }>(
      'insert into outbox (type, at, payload) values ($1, $2, $3) returning seq',
      [type, at, payload === undefined ? null : JSON.stringify(payload)],
    )
    return { seq: Number(rows[0]!.seq), type, at, ...(payload === undefined ? {} : { payload }) }
  }

  async eventsAfter(seq: number, limit: number): Promise<MachineEvent[]> {
    const { rows } = await this.db.query<EventRow>('select seq, type, at, payload from outbox where seq > $1 order by seq limit $2', [seq, limit])
    return rows.map((row) => ({
      seq: Number(row.seq),
      type: row.type,
      at: Number(row.at),
      ...(row.payload === null ? {} : { payload: JSON.parse(row.payload) as unknown }),
    }))
  }

  async dropEvents(upTo: number): Promise<void> {
    await inTransaction(this.db, async (tx) => {
      await tx.query('delete from outbox where seq <= $1', [upTo])
      // `is_called` false makes the next number the value itself, so a counter behind the hub's moves past it.
      const { rows } = await tx.query<{ next: string }>(
        `select case when is_called then last_value + 1 else last_value end as next from outbox_seq_seq`,
      )
      if (Number(rows[0]!.next) <= upTo) await tx.query(`select setval('outbox_seq_seq', $1, false)`, [upTo + 1])
    })
  }

  async lastCommand(): Promise<number> {
    const { rows } = await this.db.query<{ last: string | null }>('select max(seq) as last from commands')
    return Number(rows[0]?.last ?? 0)
  }

  commandReceived(seq: number, at: number): Promise<boolean> {
    return inTransaction(this.db, async (tx) => {
      const { rows } = await tx.query<{ last: string | null }>('select max(seq) as last from commands')
      if (seq <= Number(rows[0]?.last ?? 0)) return false
      await tx.query('insert into commands (seq, received_at) values ($1, $2)', [seq, at])
      await tx.query('delete from commands where done_at is not null and seq <= $1', [seq - KEPT_COMMANDS])
      return true
    })
  }

  async commandDone(seq: number, at: number): Promise<void> {
    await this.db.query('update commands set done_at = $2 where seq = $1 and done_at is null', [seq, at])
  }

  async unfinishedCommands(): Promise<number[]> {
    const { rows } = await this.db.query<{ seq: string }>('select seq from commands where done_at is null order by seq')
    return rows.map((row) => Number(row.seq))
  }

  async consents(): Promise<Consent[]> {
    const { rows } = await this.db.query<{ project_id: string; folder: string }>('select project_id, folder from consents order by project_id, folder')
    return rows.map((row) => ({ project: row.project_id, folder: row.folder }))
  }

  async agree(project: string, folder: string): Promise<void> {
    await this.db.query('insert into consents (project_id, folder) values ($1, $2) on conflict do nothing', [project, folder])
  }

  async withdraw(project: string, folder?: string): Promise<void> {
    if (folder === undefined) await this.db.query('delete from consents where project_id = $1', [project])
    else await this.db.query('delete from consents where project_id = $1 and folder = $2', [project, folder])
  }
}

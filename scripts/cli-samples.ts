import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { isDeepStrictEqual } from 'node:util'
import { RolloutFold } from '../src/codex/rollout.js'
import { foldEvents } from '../src/copilot/transcript.js'
import { foldSession, type MessageRow, type PartRow } from '../src/opencode/transcript.js'
import { TranscriptFold, type TranscriptSummary } from '../src/sessions/transcript.js'
import type { UsageAnswer } from '../src/limits/usage.js'
export { anonymizeSample } from './cli-sample-privacy.js'
export { compareSamples } from './cli-sample-diff.js'

export type SampleRaw = { jsonl: string } | { messages: MessageRow[]; parts: PartRow[] }
export interface CliSnapshot {
  phase: 'question' | 'answer'
  raw: SampleRaw
  expected: ReturnType<typeof sampleSummary>
}
export interface CliSample {
  provider: string
  version: string
  snapshots: CliSnapshot[]
  contextWindow: number
  /** Codex limits are replayed from the rollout; Claude's separate /usage response is kept as received by the adapter. */
  usage?: { answer?: UsageAnswer; expected: string }
}

/** Stable parser output, observed live before anonymization rather than generated by the replay. */
export function sampleSummary(summary: TranscriptSummary) {
  return {
    stage: summary.stage, asking: summary.asking, questions: summary.ask?.questions ?? null,
    checkpoint: summary.checkpoint, contextTokens: summary.contextTokens, contextWindow: summary.contextWindow,
    model: summary.model, tokens: summary.tokens,
    question: summary.ask !== null || summary.feed.some((line) => line.kind === 'text' && line.text.includes('Which colour?')),
    answer: summary.feed.some((line) => line.answers !== undefined || ((line.kind === 'answer' || line.kind === 'prompt') && line.text.trim() === 'Blue')),
    lastReply: summary.lastMessage?.includes('CHECKPOINT:') === true,
  }
}

export function replaySample(provider: string, raw: SampleRaw): TranscriptSummary {
  if (provider === 'opencode' && 'messages' in raw) return foldSession(raw.messages, raw.parts)
  if (!('jsonl' in raw)) throw new Error(`no JSONL for ${provider}`)
  if (provider === 'copilot') return foldEvents(raw.jsonl)
  const fold = provider === 'claude' ? new TranscriptFold() : provider === 'codex' ? new RolloutFold() : undefined
  if (fold === undefined) throw new Error(`unknown provider ${provider}`)
  for (const line of raw.jsonl.split('\n')) fold.push(line)
  return fold.summary()
}

/** Content-addressed runs: repeating a version never replaces earlier evidence. */
export function saveSample(root: string, sample: CliSample): string {
  for (const part of [sample.provider, sample.version]) if (!/^[a-z0-9][a-z0-9.+_-]*$/i.test(part)) throw new Error('invalid sample provider/version')
  for (const snapshot of sample.snapshots) {
    if (!isDeepStrictEqual(sampleSummary(replaySample(sample.provider, snapshot.raw)), snapshot.expected)) {
      throw new Error(`${sample.provider} ${snapshot.phase}: anonymized replay differs from the live summary`)
    }
  }
  const text = JSON.stringify(sample, null, 2) + '\n'
  const hash = createHash('sha256').update(text).digest('hex').slice(0, 16)
  const dir = join(root, sample.provider, sample.version)
  mkdirSync(dir, { recursive: true })
  const file = join(dir, `${hash}.json`)
  try { writeFileSync(file, text, { flag: 'wx' }) } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error }
  return file
}

export function loadSamples(root: string): CliSample[] {
  return readdirSync(root, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? loadSamples(join(root, entry.name)) :
    entry.name.endsWith('.json') ? [JSON.parse(readFileSync(join(root, entry.name), 'utf8')) as CliSample] : [])
}

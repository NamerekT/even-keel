"""Builds src/badge/fonts.generated.ts: the README badge's fonts, subset to the text it draws, and their glyph widths.

Usage (fontTools with Brotli: `pip install fonttools brotli`):

    python scripts/badge-fonts.py <Inter-Regular.ttf> <Inter-SemiBold.ttf> <JetBrainsMono-Regular.ttf>

The files are those of the Inter 4.1 release (`extras/ttf/`) and JetBrains Mono 2.304 (`fonts/ttf/`), both under the
SIL Open Font License; their licenses sit in `src/badge/fonts/`. Layout features are dropped, so a line is exactly the
sum of its advances and the badge cuts a title by the same table the browser draws by (docs/badge.md).
"""

import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

# Printable ASCII and the few signs the badge writes.
CHARS = "".join(chr(code) for code in range(0x20, 0x7F)) + "·…–—’×→•"
FONTS = [("sans", 400), ("sans", 600), ("mono", 400)]
OUT = Path(__file__).resolve().parent.parent / "src" / "badge" / "fonts.generated.ts"


def build(path: str) -> tuple[str, int, list[int]]:
    font = TTFont(path)
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    options.name_IDs = []
    options.hinting = False
    options.desubroutinize = True
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[ord(char) for char in CHARS])
    subsetter.subset(font)
    cmap = font.getBestCmap()
    missing = [char for char in CHARS if ord(char) not in cmap]
    if missing:
        raise SystemExit(f"{path} lacks {missing!r}")
    widths = [font["hmtx"][cmap[ord(char)]][0] for char in CHARS]
    buffer = io.BytesIO()
    font.save(buffer)
    return base64.b64encode(buffer.getvalue()).decode("ascii"), font["head"].unitsPerEm, widths


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    lines = [
        "// Generated by scripts/badge-fonts.py from Inter 4.1 and JetBrains Mono 2.304 (SIL OFL 1.1, src/badge/fonts/).",
        "// Do not edit by hand: run the script again.",
        "",
        "export interface BadgeFont {",
        "  family: 'sans' | 'mono'",
        "  weight: number",
        "  /** The subset as woff2, in base64. */",
        "  woff2: string",
        "  unitsPerEm: number",
        "  /** The advance of each character of `BADGE_CHARS`, in font units. */",
        "  widths: readonly number[]",
        "}",
        "",
        f"export const BADGE_CHARS = {CHARS!r}".replace("\\x", "\\u00"),
        "",
        "export const BADGE_FONTS: readonly BadgeFont[] = [",
    ]
    for (family, weight), path in zip(FONTS, sys.argv[1:]):
        data, units, widths = build(path)
        lines.append(f"  {{ family: '{family}', weight: {weight}, unitsPerEm: {units}, widths: [{', '.join(map(str, widths))}],")
        lines.append(f"    woff2: '{data}' }},")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
